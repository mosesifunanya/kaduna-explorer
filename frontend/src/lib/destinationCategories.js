const CATEGORY_MAP = new Map(
  DESTINATION_CATEGORIES.map((category) => [category.value, category]),
);

/**
 * Convert a category label into a URL-friendly slug.
 *
 * Example:
 * "Diagnostic Laboratory" -> "diagnostic-laboratory"
 */
export function slugifyCategoryLabel(value = "") {
  return String(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Find a built-in category by its stored value or label.
 */
export function getDestinationCategory(value) {
  const normalizedValue = slugifyCategoryLabel(value);

  if (CATEGORY_MAP.has(normalizedValue)) {
    return CATEGORY_MAP.get(normalizedValue);
  }

  return (
    DESTINATION_CATEGORIES.find(
      (category) => slugifyCategoryLabel(category.label) === normalizedValue,
    ) ?? null
  );
}

/**
 * Return a category's display label.
 *
 * Accepts either a category string or a destination object.
 */
export function getDestinationCategoryLabel(destination) {
  if (typeof destination === "string") {
    return (
      getDestinationCategory(destination)?.label ??
      (destination.trim()
        ? destination
            .trim()
            .split("-")
            .filter(Boolean)
            .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
            .join(" ")
        : "Other")
    );
  }

  if (!destination || typeof destination !== "object") {
    return "Other";
  }

  const customLabel =
    typeof destination.categoryLabel === "string"
      ? destination.categoryLabel.trim()
      : "";

  if (customLabel) {
    return customLabel;
  }

  const categoryValue =
    typeof destination.category === "string" ? destination.category : "";

  return getDestinationCategoryLabel(categoryValue);
}

/**
 * Return the stored category value from a string or destination.
 */
export function getDestinationCategoryValue(destination) {
  if (typeof destination === "string") {
    const category = getDestinationCategory(destination);

    return category?.value ?? slugifyCategoryLabel(destination);
  }

  if (!destination || typeof destination !== "object") {
    return "";
  }

  return slugifyCategoryLabel(destination.category ?? "");
}

/**
 * Check whether a value is a built-in category.
 */
export function isBuiltInDestinationCategory(value) {
  return CATEGORY_MAP.has(slugifyCategoryLabel(value));
}

/**
 * Return category options suitable for select inputs.
 */
export function getDestinationCategoryOptions({ includeOther = true } = {}) {
  const seen = new Set();

  return DESTINATION_CATEGORIES.filter((category) => {
    if (!includeOther && category.value === "other") return false;
    if (seen.has(category.value)) return false;

    seen.add(category.value);
    return true;
  });
}

/**
 * Normalize a custom category entered by an administrator.
 *
 * Store category as the slug and categoryLabel as the display
 * heading when your backend supports custom category labels.
 */
export function normalizeCustomCategory(label) {
  const cleanedLabel = String(label ?? "").trim();

  return {
    category: slugifyCategoryLabel(cleanedLabel),
    categoryLabel: cleanedLabel,
  };
}
